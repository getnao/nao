import { beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => ({
	createDraftFile: vi.fn(),
	createSafeFileAccess: vi.fn(),
	createStrictFileAccess: vi.fn(),
	readFileContent: vi.fn(),
	writeFileContent: vi.fn(),
}));

vi.mock('../../src/services/context-explorer.service', () => ({
	createDraftFile: mocks.createDraftFile,
	readFileContent: mocks.readFileContent,
	writeFileContent: mocks.writeFileContent,
}));
vi.mock('../../src/services/context-explorer-access.service', () => ({
	createSafeFileAccess: mocks.createSafeFileAccess,
	createStrictFileAccess: mocks.createStrictFileAccess,
}));

import { createContextEditorTools } from '../../src/services/context-editor-tools';

const EDITOR = { id: 'user-1', name: 'Ada', email: 'ada@example.com' };
const STRICT_ACCESS = { kind: 'strict' };
const tools = createContextEditorTools(EDITOR);

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function runTool(name: string, input: Record<string, unknown>): Promise<any> {
	// eslint-disable-next-line @typescript-eslint/no-explicit-any
	return (tools[name] as any).execute(input, {
		experimental_context: { projectId: 'project-1', projectFolder: '/tmp/project' },
		toolCallId: 'call-1',
		messages: [],
	});
}

describe('createContextEditorTools', () => {
	beforeEach(() => {
		vi.resetAllMocks();
		mocks.createStrictFileAccess.mockResolvedValue(STRICT_ACCESS);
		mocks.createSafeFileAccess.mockResolvedValue({ kind: 'safe' });
		mocks.readFileContent.mockResolvedValue({
			content: '# Orders\n\nNo notes yet.\n',
			hash: 'a'.repeat(64),
			isEditable: true,
			reason: null,
		});
	});

	it('saves an edit in the user changes against the content it read', async () => {
		await expect(
			runTool('edit_context_file', {
				path: 'docs/orders.md',
				old_string: 'No notes yet.',
				new_string: 'Paid only.',
			}),
		).resolves.toEqual({ path: '/docs/orders.md' });

		expect(mocks.createStrictFileAccess).toHaveBeenCalledWith('project-1', '/tmp/project', EDITOR);
		expect(mocks.writeFileContent).toHaveBeenCalledWith(
			'/docs/orders.md',
			'# Orders\n\nPaid only.\n',
			'a'.repeat(64),
			STRICT_ACCESS,
		);
	});

	it.each([
		{ old_string: 'Missing text', error: 'was not found' },
		{ old_string: 'O', error: 'appears several times' },
	])('refuses an edit whose text to replace is ambiguous: $error', async ({ old_string, error }) => {
		mocks.readFileContent.mockResolvedValue({ content: 'One Orders', hash: 'a'.repeat(64), isEditable: true });

		await expect(
			runTool('edit_context_file', { path: 'docs/orders.md', old_string, new_string: 'x' }),
		).rejects.toThrow(error);
		expect(mocks.writeFileContent).not.toHaveBeenCalled();
	});

	it('creates a new file in the user changes', async () => {
		await expect(
			runTool('create_context_file', { path: '/agent/skills/churn.md', content: '# Churn\n' }),
		).resolves.toEqual({ path: '/agent/skills/churn.md' });

		expect(mocks.createDraftFile).toHaveBeenCalledWith('/agent/skills/churn.md', '# Churn\n', STRICT_ACCESS);
	});

	it('tells why a file is read-only when reading it', async () => {
		mocks.readFileContent.mockResolvedValue({
			content: '- id (int)\n',
			hash: 'a'.repeat(64),
			isEditable: false,
			reason: 'generated',
			guidance: { message: 'This file is generated by nao sync.' },
		});

		await expect(runTool('read_context_file', { path: 'databases/columns.md' })).resolves.toEqual({
			path: '/databases/columns.md',
			content: '- id (int)\n',
			isEditable: false,
			readOnlyReason: 'This file is generated by nao sync.',
		});
	});
});
